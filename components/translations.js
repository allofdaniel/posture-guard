// Get device locale and set language (default to English)
export const getDeviceLanguage = () => {
  try {
    const locale = Localization.locale || 'en';
    const langCode = locale.split('-')[0].toLowerCase();
    return TRANSLATIONS[langCode] ? langCode : 'en';
  } catch {
    return 'en';
  }
};
